    # 文ごとに見る。該当表現があり除外表現がない文を探し、次の文は除く：
    #   「◯年◯月◯日付／◯年◯月◯日に…お知らせ」で、その日付が公表日と異なり、本取引（成立を条件・前提）への言及がない文（業績による無配への修正など）
    t=re.sub(r'【[^】]{0,40}】','',c['policy']+'。'+c['committee'])
    for x in re.split(r'(?<=。)|(?=\(\d{1,2}\)「)',t):   # 財務表など句点のない部分で文がつながらないよう、「(2)「…」の公表」の前でも区切る
        if not any(re.search(p,x) for p in NODIV_POS) or any(re.search(n,x) for n in NODIV_NEG): continue
        ds=re.findall(r'(\d{4})年(\d{1,2})月(\d{1,2})日(?:付|に「)',x)
        if day and ds and 'お知らせ' in x and not re.search(r'成立することを条件|前提|本取引|本公開買付け',x) and all('%s-%02d-%02d'%(y,int(m),int(d))!=day for y,m,d in ds):
            continue
        return 1,x
    return 0,''
