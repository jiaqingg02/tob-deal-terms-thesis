def rival(c):
    t = c['rival'] + '。' + c['price'] + '。' + c['board']
    t2 = t + '。' + '。'.join(c.get(s, '') for s in ['shareholder', 'committee', 'policy', 'valuation'])
    e = hitw(RIVAL_STRONG, t2, neg=STRONG_NEG, w=15) or hit(RIVAL_POS, t, neg=RIVAL_NEG)
    if e is None:   # 切り出した段落の外（売主側の売却先選定の経緯）にだけ書かれている場合：原文全体で「売却先候補N社」に限って探す
        full = '。'.join(''.join(pg) for _, _, pg in c.get('_full', []))
        e = hit([r'(売却先|譲渡先|買収)候補[0-9０-９二三四五六七八九十数]+社(に対して|に対し|に)'], full, neg=[r'場合|仮に|一般に|事例'])
    return R(e)


# ---------------------------------------------------------------- 3 交渉で値上げされていない
# 定義：交渉の過程で買付価格が引き上げられていない（据え置き・引き下げ・未合意を含む）。二段階の公開買付けでは、どちらかの段階で引き上げがあれば「引き上げあり」とする
def proposals(t, pos=False, year=None):
    """「本公開買付価格をX円」「X円とする旨の提案」の価格を出現順に抜き出す。次のものは除く：
       新株予約権・終値・算定・自己株式取得価格・譲渡価格などの数字；対象者側の要望価格（「X円とすることを…要請」）；
       公表年より2年以上前の古い価格。pos=True のときは (価格, 位置) を返す"""
    out = []
    pat = (r'(?:(?<!新株予約権)(?:本公開買付価格|公開買付価格|買付価格|買付け等の価格)(?:を|について|は|が|である)?(?:1株(?:当たり|につき))?|1株(?:当たり|につき))([0-9][0-9,]{1,8})円'
           r'|([0-9][0-9,]{1,8})円(?:を本公開買付価格と|とする旨の(?:再|最終)?提案|とする(?:再|最終)?提案)')
    for m in re.finditer(pat, t):
        pre = t[max(0, m.start() - 12):m.start()]
        if re.search(r'新株予約権|終値|平均|算定|範囲|純資産|譲渡価格|自己株式取得|取得価格|株式交換', pre):
            continue
        post = t[m.end():m.end() + 45]
        if re.search(r'^(以上)?(に|へ|と)?[^。]{0,25}(要請|検討するよう|求め|要望|希望)', post) and not re.search(r'^[^。]{0,25}(提案|提示)', post):
            continue   # 対象者側が求めた価格
        if year:
            ys = [int(y) for y in re.findall(r'(20[0-9]{2}|19[0-9]{2})年', sent(t, m.start()))]
            if ys and max(ys) < year - 1: continue   # かなり以前の売買価格
        v = int((m.group(1) or m.group(2)).replace(',', ''))
        if 10 <= v <= 200000:
            out.append((v, m.start()) if pos else v)
    return out


# 最終の買付価格（書類からプログラムで抽出済み。premium.csv）
_P = _pd.concat([_pd.read_csv(os.path.join(DATA, 'data/analysis/premium.csv'), dtype={'target_code': str}),
                 _pd.read_csv(os.path.join(DATA, 'data_old/analysis/premium.csv'), dtype={'target_code': str})])
FINAL = dict(zip(_P.target_code + '_' + _P.event_date, _P.price_yen))

# 価格が引き上げられたことを直接述べる文
RAISE_TXT = [r'(引き上げ|引上げ|増額|上積み|上乗せ)(られ|た(?!い)|後の|を行っ|した|された)', r'(引き上げ|引上げ|増額)(る|た)旨の(再)?提案', r'円(に|へ)(と)?(引き上げ|引上げ|増額)',
             r'当初(の)?(提案)?(価格)?(から|より|比|に比べ)[^。]{0,25}(引き?上げ|上昇|上回|増額|[0-9.]+%)', r'初回(提示|提案)[^。]{0,25}から', r'(引上げ|引き上げ|増額)を引き出',
             r'増額を図った', r'[0-9０-９二三四五六七八九]回に(亘|わた)る[^。]{0,15}(引上げ|引き上げ|増額)', r'再提案価格', r'円、[0-9,]+円と(引上げ|引き上げ)', r'上乗せした']
# 要望・仮定・拒否の文は「引き上げられた」としない
RAISE_NEG = [r'困難|応じ(られ)?ない|応じなかった|見送|できない|据え置|変更しない|行わない|場合|仮に|求め|要請|要望|検討するよう|可能性|余地|引上げを行わず|新株予約権|配当|株式分割|下限|同額|自己株式取得']
# 対象者（または特別委員会）が引上げ・再検討を求めた記載
TARGET_ASK = r'(引上げ|引き上げ|増額|再検討|再考|再提案|見直し)[^。]{0,30}(要請|求め|要望|検討するよう|申し入れ)|(要請|求め)を受け|応諾がなされなかった'
# 新たな提案の後に「これ以上は引き上げない」と述べる文
NO_MORE = r'同額|と同じ|変更しない|据え置|余地はない|困難|できない|応じられない|維持する'
# 入札段階・売主の大株主との交渉で決まった価格（対象者との交渉による引上げではないので数えない）
SIDE = r'入札|意向表明書|第[一二1-2]次|候補|(?<!不)応募合意株主|(?<!不)応募予定株主|大株主|売主|創業家|親会社(から|との間)|株主との間'


def price_raised(c):
    """対象者（特別委員会）との交渉の過程で、買付価格が引き上げられた。判定方法：
       (a) 抜き出した提案価格の中に最終の買付価格より低いものがある（入札段階・売主との交渉の価格は除く）
       (b)「引き出した」「当初比X%」「N回に亘る引上げ」「上乗せした」など、引上げを直接述べる文がある
       (c) 対象者が引上げ・再検討を求めた後に、買付者が「改めて検討した結果」新たな価格を提示した"""
    t = c['price']; f = FINAL.get(c['_key']); year = int(c['_key'].split('_')[1][:4])
    ps = [(v, p) for v, p in proposals(t, True, year) if not re.search(SIDE, sent(t, p))]   # 入札段階・売主との交渉の価格は数えない
    vals = [v for v, _ in ps]
    # 最終価格：premium.csv は文中で最初に現れた買付価格を記録しており、初回提案価格や株式分割調整後の価格のこともある。
    # そのため通常は「文中の提案価格の最高値」を用いる。引き下げ・減額の記載があるときは記録された最終価格を用いる
    if vals:
        ref = max(sorted(vals)[len(vals) // 2], f if (f and f == f) else 0)
        ok = [v for v in vals if v <= 1.25 * ref]   # 中央値・記録価格より25%以上高いものは、多くが対象者側の要望価格である
        top = max(ok)
        if f and f == f and f in vals and re.search(r'引き?下げ|減額', t): pass
        else: f = max(top, f) if (f and f == f and f <= 1.25 * top) else top
    low = [(v, p) for v, p in ps if 0.5 * f <= v < f * 0.999]
    if low:
        v, p = min(low)
        return 1, ev(f'提案価格 {v}円→最終 {int(f)}円：' + sent(t, p), '提案価格が最終価格より低い')
    e = hit(RAISE_TXT, t, neg=RAISE_NEG)
    if e: return 1, e
    e = hit([r'協議・交渉を重ねて(まいりました|きました)。[^。]{0,60}最終提案を行'], t, neg=[NO_MORE])   # 協議・交渉を重ねた後に最終提案が行われた
    if e: return 1, ev(e, '協議・交渉を重ねた後の最終提案')
    e = hit([r'本公開買付価格の引き上げをするためには[^。]{0,300}本公開買付価格を[0-9,]+円[^。]{0,250}再度提案'], t)   # 価格を引き上げるためにスキームを変更して再提案した
    if e: return 1, ev(e, '価格を上げるためにスキームを変えて再提案')
    # (c) 対象者の引上げ・再検討の要請 → 買付者が改めて検討して新たな価格を提示（同額・余地なしの記載がない）
    for m in re.finditer(TARGET_ASK, t):
        nxt = t[m.end():m.end() + 300]
        q = re.search(r'(改めて|再度|真摯に)(検討|精査|協議)[^。]{0,60}(本公開買付価格|公開買付価格)を(1株(当たり|につき))?[0-9,]+円'
                      r'|これに対し[^。]{0,40}(本公開買付価格|公開買付価格)を[0-9,]+円(?:[^。]|。\)){0,150}(とすることを提案|とする旨の提案|を提案)'
                      r'|再提案\(以下「第[2-9２-９二三四五六七八九]回提案'
                      r'|最終提案を行', nxt)
        if q and not re.search(NO_MORE, nxt[:q.end() + 60]) and not re.search(NO_MORE, sent(nxt, q.start())):
            return 1, ev(sent(t, m.end() + q.start()), '要請の後に改めて検討した新しい提案価格')
    return 0, ''


def no_raise(c):
    r, s = price_raised(c)
    if r:
        return 0, s
    # 引上げなし：参考として「据え置き」「これ以上は困難」などの文があれば根拠文とする
    return 1, hit([r'(価格|本公開買付価格)[^。]{0,20}据え置', r'これ以上の(引上げ|引き上げ|増額)は(困難|できない)',
                   r'(引上げ|引き上げ|増額)(の要請)?(には|に)応じ(られ)?ない'], c['price']) or '提案価格は1通りで、引き上げの記載なし'


# ---------------------------------------------------------------- 4 株主優待の廃止
# 定義：今後の方針に株主優待（制度）を廃止すると書かれている
def perk_abolish(c):
    t = re.sub(r'【[^】]{0,40}】', '', c['policy'] + '。' + c['committee'])   # 【見出し】は除く
    return R(hit([r'株主優待[^。]{0,60}(廃止|取りやめ|終了|継続しない|実施しない|行わない)', r'(廃止|取りやめ)[^。]{0,20}株主優待'], t,
                 neg=[r'場合には|不成立|撤回|継続する(予定|方針)|維持する|上場廃止|ご参照']))


# ---------------------------------------------------------------- 5 親子上場の解消
# 定義：親会社（支配株主）が上場子会社の残りの株式を全て取得する。部分買付けと MBO（経営者が支配株主）は除く
def parent_sub(c):
    t = _all(c)
    # 買付者が親会社（支配株主）であることを明記した表現。「支配株主との取引等に該当」とだけあり買付者が親会社でない場合（親会社が売主など）は含めない
    e = hit([r'(当社|対象者)が公開買付者の(連結)?子会社であ', r'公開買付者(が|は)(当社|対象者)の(親会社|支配株主)(\(親会社\))?(であり|であるため|であること|であって|に該当)',
             r'公開買付者は、?[^。]{0,40}所有割合[^。]{0,20}に達する(当社|対象者)の支配株主', r'親会社である■■による(当社|対象者)(普通)?株(式|券等?)に対する公開買付け', r'(当社|対象者)の親会社である■■を公開買付者とし',
             r'公開買付者の(完全)?親会社である[^。]{0,40}(は|が)[^。]{0,60}(当社|対象者)(普通)?株式[0-9,]+株\(所有割合',
             r'(当社|対象者)の支配株主(\(親会社\))?であり、本公開買付け',
             r'(支配株主|親会社)(\(親会社\))?である■■\(以下「公開買付者」', r'公開買付者は[^。]{0,150}(当社|対象者)を連結子会社として',
             r'公開買付者の(完全)?親会社である[^。]{0,80}(当社|対象者)を連結子会社', r'を所有する親会社であ', r'親子上場(の解消|関係の解消|に伴う)'], t,
            neg=[r'該当(しない|せず|しません|いたしません)', r'仮に', r'事例', r'一般に', r'応募合意株主|応募予定株主'])
    strong = e is not None and re.search(r'子会社であ|親会社|支配株主', e) and (re.search(r'公開買付者', e) or 'を所有する親会社であ' in e)
    if e and (partial(c)[0] or (mbo_any(c)[0] and not strong)):   # 部分買付けは除く。MBO も除くが、買付者が親会社だと明記されているものは除かない
        return 0, ''
    return R(e)


# ---------------------------------------------------------------- 6 取締役会が中立
# 定義：賛同するが、応募するか否かは株主の判断に委ねる（応募を推奨しない）。反対・意見の留保もここに含める（生成AIの集計と同じ扱い）
def board_neutral(c):
    return R(hit([r'応募するか否か(について)?は、?(当社|対象者)?の?株主(の皆様|の皆さま)?((及び|並びに)[^。]{0,40})?(の|のご)判断に委ね', r'中立の立場',
                  r'応募を推奨(すること)?(は|を)(せず|しない|行わない|差し控え|留保)', r'反対(の|する旨の)意見を表明', r'意見(の表明)?を留保'],
                 c['board'], neg=[r'場合', r'仮に', r'前回', r'撤回', r'とき(で|に|は)']))


# ---------------------------------------------------------------- 7 大株主の応募契約なし
# 定義：株主との応募・不応募の契約・合意の記載がない
def no_holder_agreement(c):
    t = c['shareholder'] if len(c['shareholder']) > 200 else _all(c)   # 2019・2021年の適時開示ではこの段が空のことがある → すべての段落を見る
    t = re.sub(r'【[^】]{0,40}】', '', t)                               # 【応募契約の…】などの見出しは除く
    e = hitw([r'(応募|不応募)(に関する|に係る)?(契約|合意書|覚書)', r'応募(する|しない)(旨の|意向|ことに(合意|同意))', r'応募(を指図しない|しない|せず)', r'(応募|不応募)(予定|合意)株主', r'不応募',
              r'(応募|譲渡|売却)[^。]{0,20}(合意|同意)(して|いたし|し、|した)', r'指図しないこと', r'現物配当契約', r'自己株式取得に応じ', r'相対(で)?譲渡'], t,
             neg=[r'締結して(い)?(ない|おりません)|該当事項はありません|存在しない|予定はない|場合|仮に|一般|推奨|マジョリティ|下限|譲渡制限|承認を要する|新株予約権|買取請求権|価格決定|応募しないよう|をしておりません|表明'], w=12)
    if e and re.search(r'(締結した|合意した)株主(も|は)(存在しない|おりません|いない)', e):   # 「応募契約を締結した株主も存在しない」という否定
        e = None
    if not e:   # 他の段（取締役会の意見・買付けの構造など）に「○年○月○日付で、□□との間で、…応募しない」とある場合
        e = hit([r'[0-9]+年[0-9]+月[0-9]+日付で[^。]{0,40}との間で[^。]{0,120}(応募しない|応募せず|応募する旨|不応募|現物配当契約|応募契約|株式譲渡)',
                 r'(株式譲渡|相対取引)により取得する予定', r'公開買付者らが共同して'], _all(c), neg=[r'場合|仮に|前回|過去|対抗|表明'])
    return (0, e) if e else (1, '応募・不応募の契約の記載なし')


# ---------------------------------------------------------------- 8 自己資金
# 定義：買付資金に借入・出資の予定がない（届出書の資金欄 (b)(c)(d) がすべて空欄、または本文に自己資金と明記）
def self_funded(c):
    t = c['funding']
    if '【届出日以後に借入れを予定している資金】' in t or '計(b)' in t:   # 公開買付届出書（資金の表がある）
        z = lambda lab: re.search(r'計\(' + lab + r'\)\s*([0-9][0-9,]*)', t)
        if z('b') or z('c') or z('d'):
            return 0, ''
        e = hit([r'融資証明書|出資証明書|引受証明書|融資を行う用意|出資を行う用意|貸付実行'], t)
        group = re.search(r'(親会社|完全子会社|子会社|グループ会社)[^。]{0,40}(借入|融資|貸付|金銭消費貸借)|(借入|融資|貸付)[^。]{0,40}(親会社|完全子会社|子会社)'
                          r'|公開買付者の(完全)?(子会社|親会社)です|公開買付者の株式の全てを所有する親会社', t)
        if e and not group:   # 表の合計欄に記入漏れがあっても、融資・出資証明書があれば借入・出資あり（同一グループ内からの借入は自己資金とみなす）
            return 0, e
        m = re.search(r'(当座預金|普通預金|定期預金|預金|預け金|預託金)(\([^)]{0,20}\))*\s*([0-9][0-9,]*)', t)
        if m: return 1, ev(t[max(0, m.start() - 60):m.end() + 400], '預金あり・借入／出資の予定欄が空欄')
        if group: return 1, ev(sent(t, group.start()), '同じグループ内からの借入のみ')
        return 0, ''
    # 適時開示（資金の表がない）：本文のうち買付資金について書いた文だけを見る。買付資金の記載がなければ「記載なし」（欠測）とし、0（借入・出資あり）とは区別する
    fs = [x for x in (sent(t, m.start()) for m in re.finditer(r'(本公開買付け|買付け等|買付|決済|本取引)[^。]{0,30}(資金|代金)|(資金|代金)[^。]{0,30}(本公開買付け|買付け等|決済)', t))
          if not re.search(r'運転資金|設備資金|対象者は', x)]   # 対象者自身の借入など、買付資金でない文は除く
    if not fs:
        return float('nan'), ''
    for x in fs:
        if re.search(r'自己資金|手元資金|現預金', x) and not re.search(r'借入|融資|ローン|貸付|出資', x):
            return 1, ev(x, '買付資金：自己資金')
    for x in fs:
        if re.search(r'(親会社|完全親会社|完全子会社|子会社|グループ会社)[^。]{0,40}(借入|融資|貸付)|(借入|融資|貸付)[^。]{0,40}(親会社|完全親会社)', x):
            return 1, ev(x, '買付資金：同じグループ内からの借入のみ（届出書と同じ扱い）')
        if re.search(r'借入|融資|ローン|貸付|出資', x):
            return 0, ev(x, '買付資金：借入・出資あり')
    return float('nan'), ''


# ---------------------------------------------------------------- 9 許認可の承認待ち
# 定義：独占禁止法・外為法の待機期間以外に、金融庁・海外当局などの許可・承認が必要で、届出時点で得られていない（外為法・独禁法は事前届出の待機であり許可・承認ではないため含めない）
def reg_pending(c):
    t = c['regulatory'] + '。' + c['shareholder']
    i = t.find('取得に関する許可等】'); t = t[i:] if i >= 0 else t
    # 海外の競争当局・投資審査
    e = hit([r'(ACCC|韓国公取委|閣僚理事会|競争委員会|競争庁|カルテル庁|競争当局|投資審査|外国直接投資|資本移動)[^。]{0,80}(承認|免除決定|回答|クリアランス|審査)[^。]{0,40}(得られない|取得できない|取得できていない|得られなかった|決定を行います|審査期間内|受けられなかった)'],
            t, neg=[r'取得しております|受領しております|終了しております|完了しております'])
    if e:
        return R(e)
    # 国内の認可・承認（金融庁など）
    pos = [r'(認可|承認|許可)[^。]{0,60}(正式)?申請を行う予定',
           r'(認可|承認|許可|審査が終了した旨の通知)[^。]{0,40}(を)?(受け|取得|得)(ることが)?(られなかった|できなかった|できていない)場合',
           r'(認可|承認|許可)(を|が)(取得して|受けて|得て)(いない|おりません|おらず)', r'(認可|承認|許可)の取得(を|が)(待|未了|見込)',
           r'(海外|外国|米国|欧州|EU|中国|韓国|台湾|ベトナム|ドイツ|オーストリア|英国|スウェーデン|[^。]{0,6}国)[^。]{0,40}(競争当局|競争法|当局|投資規制|投資審査)[^。]{0,60}(承認|クリアランス|免除|許可|審査期間)[^。]{0,40}(場合|未取得|得られて)']
    return R(hit(pos, t, neg=[r'独占禁止法|公正取引委員会(?!の認可)|措置期間|取得禁止期間|該当事項はありません|外為法|外国為替|株主総会|株式交換契約']))


