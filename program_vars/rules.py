FUND_SELLER = r'応募合意株主|応募予定株主|不応募合意株主|応募株主|応募契約|応募する旨'   # 文全体にあれば、そのファンドは売主・応募する株主


def _flat(t):
    """括弧の中の句点（「(以下「X」といいます。)」など）を除き、括弧の途中で文が切れないようにする（閉じ括弧が200字以内にない場合は除かない）"""
    out, i = [], 0
    for m in re.finditer(r'[(「][^()「」]{0,200}(?:[(「][^()「」]{0,200}[)」][^()「」]{0,200})*[)」]', t):
        out.append(t[i:m.start()]); out.append(m.group(0).replace('。', '')); i = m.end()
    out.append(t[i:])
    return ''.join(out)


def bidder_parts(c):
    """原文PDFから買付者に関する部分を取り出す：名称・大株主欄（届出書／適時開示）・会社の目的・買付けの目的の冒頭・買付資金欄"""
    g = {'name': [], 'holder': [], 'holder_t': [], 'type': [], 'chain': [], 'money': []}
    for kind, d, pages in c.get('_full', []):
        t = _flat(''.join(pages))
        m = re.search(r'【届出者の氏名又は名称】(.{0,120}?)【', t)
        if m: g['name'].append(m.group(1))
        for m in re.finditer(r'会社名(.{0,60}?)代表者', t[:3000]):     # 適時開示の冒頭（共同公表する会社の名称）
            g['name'].append(m.group(1))
        i = t.find('公開買付者の状況】')
        if i >= 0:
            j = t.find('【大株主】', i); e = t.find('【役員', j)
            if 0 <= j - i < 6000:
                g['type'].append(t[i:j]); g['holder'].append(t[j:(e if 0 < e - j < 3000 else j + 1500)])
        for m in re.finditer(r'公開買付者の概要', t):                 # 適時開示（2019・2021年）の「公開買付者の概要」の表
            b = t[m.start():m.start() + 1500]
            n = re.search(r'\(1\)名称(.{0,80}?)\(2\)', b)
            if n: g['name'].append(n.group(1))
            h = re.search(r'大株主及び持株比率(.{0,300}?)(\(8\)|上場会社と)', b)
            if h: g['holder_t'].append(h.group(1))
        k = t.find('本公開買付けの概要'); j = t.find('公開買付者は、', k if k >= 0 else 0)
        if j >= 0: g['chain'].append(t[j:j + 2500])
        k = t.find('【買付け等に要する資金】')
        if k >= 0: g['money'].append(t[k:k + 4000])
    return {s: '。'.join(v) for s, v in g.items()}


def fund(c):
    """買付者がファンド
    定義：買付者（本件のために設立された SPC を含む）が PE ファンド・投資ファンド（投資事業有限責任組合、リミテッド・パートナーシップ、EQT・ベイン・KKR・J-STAR などの PE 会社が運営するもの）に
          所有・支配・運営されている、または買付資金がファンドの出資（優先株式・種類株式の引受けを含む）で賄われる。
          本文に出てくるだけのパッシブ・インデックス運用ファンド、応募する株主・売主にすぎないファンド、対抗提案者、事業会社の VC 事業、一般的な言及は含めない。
          ファンドからの融資（メザニン融資を含む）と、決済後の借入金のリファイナンスは出資ではないので含めない"""
    g = bidder_parts(c)
    # (a) 買付者自体がファンド（届出者の名称が投資事業有限責任組合・L.P. など）
    m = re.search(FUND_TERM, g['name'])
    if m:
        return 1, ev(g['name'][max(0, m.start() - 60):m.end() + 20], '買付者の名称がファンド')
    # (b) 買付者の【大株主】欄にファンド（所有割合20%以上。割合の記載がない合同会社の社員を含む）。適時開示の表は名称の直後の割合だけを見る
    for h, num, w in [(g['holder'], r'(\d{1,3}\.\d{1,2})(?!\d)', 160), (g['holder_t'], r'(\d{1,3}(?:\.\d+)?)%', 30)]:
        for m in re.finditer(FUND_ANY, h):
            r = re.search(num, h[m.end():m.end() + w])
