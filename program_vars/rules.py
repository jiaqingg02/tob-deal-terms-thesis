# ============================================================================
# 公開買付けの取引条件をプログラムで判定する規則（生成AIは用いない）
#
# このファイルの役割：
#   公開買付届出書と意見表明報告書（2019・2021年の一部は適時開示）の記載から、
#   論文で用いる11の取引条件を、キーワード（正規表現）と数値の規則だけで 0/1 に判定する。
#   判定する条件と関数の対応は次のとおりである。
#     1 部分買付け            partial            7 大株主の応募契約なし    no_holder_agreement
#     2 入札・競合あり        rival              8 自己資金                self_funded
#     3 交渉で値上げされていない no_raise        9 許認可の承認待ち        reg_pending
#     4 株主優待の廃止        perk_abolish      10 買付者がファンド        fund
#     5 親子上場の解消        parent_sub        11 MBO（ファンドなし）     mbo
#     6 取締役会が中立        board_neutral     （参考）無配化            no_dividend（分析には未使用）
#   規則は人手で書いたものであり、同じ入力からは常に同じ結果が得られる（再現可能）。
#
# 入力：1案件分の書類の段落をまとめた dict（以下 c）。corpus.load() で読み込む。
#       段落の切り出し方は、比較のために生成AIに読ませた段落と同一である。キーと内容は次のとおり。
#       公開買付届出書の7段：
#         price       買付価格の決定経緯・価格交渉
#         rival       対抗提案・入札の経緯
#         board       対象者の取締役会の意見
#         shareholder 大株主との応募・不応募の合意
#         funding     買付けに要する資金（資金の表と借入・出資の予定）
#         regulatory  許認可等（独占禁止法・外為法・海外当局など）
#         structure   買付けの構造（買付予定数の上限・下限）
#       意見表明報告書の4段：
#         committee   特別委員会の答申
#         policy      今後の方針（上場の維持・廃止、配当、株主優待）
#         valuation   買付価格とその算定
#         mom         買付予定数の下限（マジョリティ・オブ・マイノリティ条件）
#       c['_key']：「対象者の証券コード_公表日」。最終の買付価格（premium.csv）との対応付けに用いる
#       c['_full']：原文PDFの全文（ページ単位）。段落の切り出しから漏れやすい記載
#                   （買付者の大株主欄、売主側の売却先選定の経緯）を読むときにだけ用いる
#
# 出力：条件ごとに1つの関数があり、(判定, 根拠文) を返す。判定は 1（条件に当てはまる）または 0。
#       self_funded だけは、買付資金の記載が見つからないとき NaN（欠測）を返す。
#       根拠文は判定の根拠となった原文の1文であり、その属性 .pat には該当した規則（正規表現または説明）が入る。
#       根拠文を残すのは、判定結果を一件ずつ原文と突き合わせて検証できるようにするためである。
#
# 判定の基本的な考え方：
#   該当表現（pos）：文中に現れれば 1 と判定する表現（正規表現）
#   除外表現（neg）：該当表現と同じ文（または近く）に現れれば、その文を根拠としない表現
#   書類には「〜の場合には」「一般に〜」「〜は行っておりません」のように、該当表現を含みながら
#   事実としては当てはまらない文が多い。そこで、否定・仮定・一般論・過去の事例を表す語を除外表現とし、
#   該当表現があっても除外表現と同じ文にあるものは根拠としない。
# ============================================================================
import os
import re
import pandas as _pd

DATA = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')   # データのフォルダ（このファイルの1つ上）


# ---------------------------------------------------------------- 共通の関数
class Ev(str):
    """根拠文。文字列として扱えるうえ、該当した規則を属性 .pat に持つ"""
    pat = ''


def ev(s, p):
    """文 s を根拠文とし、該当した規則 p を .pat に記録して返す"""
    e = Ev(s); e.pat = p
    return e


def sent(t, i):
    """位置 i を含む1文を取り出す（「。」または「…」で区切る。最大300字）"""
    a = max(t.rfind('。', 0, i), t.rfind('…', 0, i)) + 1
    b = t.find('。', i); b = len(t) if b < 0 else b + 1
    return t[a:b][:300]


def hit(pats, t, neg=()):
    """該当表現を順に探し、該当した文に除外表現がなければその文を返す。見つからなければ None"""
    for p in pats:
        for m in re.finditer(p, t):
            s = sent(t, m.start())
            if not any(re.search(n, s) for n in neg):
                return ev(s, p)
    return None


def hitw(pats, t, neg=(), w=35):
    """hit と同じだが、除外表現は該当箇所の前後 w 字以内（同じ文の中）だけで確認する。
       書類の文は長く、一文の中で事実の記載と別の事柄の否定が並ぶことがある。
       文全体で除外すると事実の記載まで落としてしまうため、否定が該当箇所にかかる範囲に限って確認する"""
    for p in pats:
        for m in re.finditer(p, t):
            s = sent(t, m.start())
            a = max(t.rfind('。', 0, m.start()) + 1, m.start() - w)
            end = t.find('。', m.end()); b = min(m.end() + w, end if end >= 0 else len(t))
            if not any(re.search(n, t[a:b]) for n in neg):
                return ev(s, p)
    return None


def R(s):
    """根拠文が見つかれば (1, 根拠文)、見つからなければ (0, '') を返す"""
    return (int(s is not None), s or '')


def _all(c):
    """すべての段落を句点でつなげる。キーが「_」で始まるもの（原文PDF・案件キー）は除く"""
    return '。'.join(v for s, v in c.items() if not s.startswith('_'))


# ---------------------------------------------------------------- 1 部分買付け
def partial(c):
    """部分買付け。1 = 対象者の株式の全部ではなく一部だけを取得する公開買付けである。
    見る段：structure（買付けの構造）。上場維持の記載が見つからなければ board（取締役会の意見）と policy（今後の方針）も見る。
    1 とするのは次のいずれかである。
      (a) 買付予定数の表の「上限」欄に株数が記入されている
      (b) 本文に「上限(N株)を超える場合」「あん分比例の方式により」とある
      (c) 上限はないが「上場廃止を企図するものではなく」「上場を維持する方針」と明記している
    除外表現：「上限を設定しておりません」は上限がないことの記載である。「超えなかった」「行いました」は
    過去の公開買付けの結果の説明である。また、不成立の場合の説明、買付者の親会社（持株会社）や
    買付者自身の株主の上場の話は、本件の対象者の上場維持ではないので根拠としない"""
    t = c['structure']
    # (a) 表「買付予定数／下限／上限」の3つ目が数字 → 上限あり
    tab = None
    for m in re.finditer(r'買付予定数の上限(?:普通株式)?([0-9,]+|[―\-−])\(?株\)?([0-9,]+|[―\-−])\(?株\)?([0-9,]+|[―\-−])', t):
        if re.match(r'[0-9]', m.group(3)):
            tab = sent(t, m.start()); break
    # (b) 本文に「上限(N株)を超える場合」「あん分比例の方式」とある
    cap = tab or hit([r'上限\([0-9,]+株(\(所有割合[^)]*\))?\)(を超える|以下)', r'あん分比例の方式により'], t,
                     neg=[r'上限を設定して(おりません|いない|いません)', r'上限を設けて(おりません|いない)', r'超えなかった', r'行いました'])
    # (c) 上限はないが、上場廃止を企図せず上場を維持すると明記（上場維持型の部分取得）
    keep = hit([r'上場廃止を企図(する|した)もの(では|で)(なく|ありません|はありません)', r'上場を維持する(方針|予定)', r'上場が維持される(予定|見込み)'], t,
               neg=[r'不成立', r'企図しておりますが', r'場合には', r'持株会社', r'公開買付者の株主'])
    if not keep:   # 買付けの構造の段に記載がなければ、取締役会の意見・今後の方針を見る
        keep = hit([r'(当社|対象者)株式の上場廃止を企図(する|した)もの(では|で)(なく|ありません|はありません)', r'(当社|対象者)株式の上場が維持される(予定|方針)'],
                   c['board'] + c['policy'], neg=[r'不成立', r'場合には', r'持株会社'])
    return R(cap or keep)


