def _flat(t):
    """括弧の中の句点（「(以下「X」といいます。)」など）を除き、括弧の途中で文が切れないようにする（閉じ括弧が200字以内にない場合は除かない）"""
    out, i = [], 0
    for m in re.finditer(r'[(「][^()「」]{0,200}(?:[(「][^()「」]{0,200}[)」][^()「」]{0,200})*[)」]', t):
        out.append(t[i:m.start()]); out.append(m.group(0).replace('。', '')); i = m.end()
    out.append(t[i:])
    return ''.join(out)


def bidder_parts(c):
    """原文PDFから買付者に関する部分を取り出し、種類ごとに句点でつないだ dict で返す。
       name 届出者・買付者の名称、holder 届出書の【大株主】欄、holder_t 適時開示の「大株主及び持株比率」欄、
       type 【公開買付者の状況】の会社の目的など、chain 「本公開買付けの概要」の冒頭（所有関係の説明）、money 【買付け等に要する資金】欄"""
    g = {'name': [], 'holder': [], 'holder_t': [], 'type': [], 'chain': [], 'money': []}
    for kind, d, pages in c.get('_full', []):
        t = _flat(''.join(pages))
        m = re.search(r'【届出者の氏名又は名称】(.{0,120}?)【', t)
        if m: g['name'].append(m.group(1))
        for m in re.finditer(r'会社名(.{0,60}?)代表者', t[:3000]):     # 適時開示の冒頭（共同公表する会社の名称）
            g['name'].append(m.group(1))
        i = t.find('公開買付者の状況】')
        if i >= 0:
            j = t.find('【大株主】', i); e = t.find('【役員', j)
            if 0 <= j - i < 6000:
                g['type'].append(t[i:j]); g['holder'].append(t[j:(e if 0 < e - j < 3000 else j + 1500)])
        for m in re.finditer(r'公開買付者の概要', t):                 # 適時開示（2019・2021年）の「公開買付者の概要」の表
            b = t[m.start():m.start() + 1500]
            n = re.search(r'\(1\)名称(.{0,80}?)\(2\)', b)
            if n: g['name'].append(n.group(1))
            h = re.search(r'大株主及び持株比率(.{0,300}?)(\(8\)|上場会社と)', b)
            if h: g['holder_t'].append(h.group(1))
        k = t.find('本公開買付けの概要'); j = t.find('公開買付者は、', k if k >= 0 else 0)
        if j >= 0: g['chain'].append(t[j:j + 2500])
        k = t.find('【買付け等に要する資金】')
        if k >= 0: g['money'].append(t[k:k + 4000])
    return {s: '。'.join(v) for s, v in g.items()}


def fund(c):
    """買付者がファンド。1 = 買付者（本件のために設立された SPC＝特別目的会社を含む）が PE ファンド・投資ファンド
    （投資事業有限責任組合、リミテッド・パートナーシップ、EQT・ベイン・KKR・J-STAR などの PE 会社が運営するもの）に
    所有・支配・運営されている、または買付資金がファンドの出資（優先株式・種類株式の引受けを含む）で賄われる。
    見る箇所：bidder_parts で取り出した原文PDFの部分。(a)名称 →(b)大株主欄 →(c)会社の目的 →(d)買付資金 →(e)所有関係の説明
    の順に探し、最初に見つかった根拠で 1 とする。
    除外表現：ファンドの名前は、買付者の所有者でない立場でも書類に多く現れる。本文に出てくるだけのパッシブ・インデックス運用ファンド、
    応募する株主・売主にすぎないファンド、対抗提案者、事業会社の VC 事業、一般的な言及は含めない。
    ファンドからの融資（メザニン融資を含む）と、決済後の借入金のリファイナンスは出資ではないので含めない"""
    g = bidder_parts(c)
    # (a) 買付者自体がファンド（届出者の名称が投資事業有限責任組合・L.P. など）
    m = re.search(FUND_TERM, g['name'])
    if m:
        return 1, ev(g['name'][max(0, m.start() - 60):m.end() + 20], '買付者の名称がファンド')
    # (b) 買付者の【大株主】欄にファンドがある（所有割合20%以上。割合の記載がない合同会社の社員を含む）。
    #     適時開示の表は、他の株主の割合と混同しないよう名称の直後の割合だけを見る
    for h, num, w in [(g['holder'], r'(\d{1,3}\.\d{1,2})(?!\d)', 160), (g['holder_t'], r'(\d{1,3}(?:\.\d+)?)%', 30)]:
        for m in re.finditer(FUND_ANY, h):
            r = re.search(num, h[m.end():m.end() + w])
            if (r is None and w == 160) or (r and float(r.group(1)) >= 20):
                return 1, ev(h[max(0, m.start() - 60):m.end() + w], '買付者の大株主がファンド')
    # (c) 買付者自体が投資信託・投資会社・投資事業有限責任組合（会社の目的・団体の沿革）
    m = re.search(r'クローズドエンド型投資会社|インベストメント・トラスト|投資事業有限責任組合契約に関する法律に基づ', g['type'])
    if m:
        return 1, ev(g['type'][max(0, m.start() - 80):m.end() + 40], '買付者自体が投資ファンド')
    # (d) 買付資金：ファンドの出資証明書、ファンドによる優先株式・種類株式の引受けによる出資（リファイナンスは除く）
    e = hitw([r'(' + FUND_ANY + r')[^。]{0,80}(から|より)[^。]{0,60}出資を行う用意', r'(' + FUND_ANY + r')[^。]{0,60}による[^。]{0,250}株式[^。]{0,120}の引受け?による[^。]{0,30}出資'],
             g['money'] + '。' + g['chain'], neg=[r'リファイナンス'], w=60) \
        or hitw([r'(' + FUND_ANY + r')[^。]{0,40}(から|より)[^。]{0,30}出資を受け'], g['chain'], neg=[r'リファイナンス|融資|借入|貸付'], w=60)
    if e:
        return 1, e
    # (e) 買付けの目的の冒頭で、ファンドが買付者（親会社・祖父母会社を含む）を所有・運営すると書かれている
    #     条件：同じ文に所有・運営の語があり、かつ「公開買付者」または「発行済株式（議決権・持分）の全て／○%」があること。
    #     除外表現はファンド名の前後40字で確認し、売主・応募株主を表す語（FUND_SELLER）は文全体で確認する
    t = g['chain']
    for m in re.finditer(FUND_ANY + r'|投資の目的で[^。]{0,20}組成された', t):
        a0 = t.rfind('。', 0, m.start()) + 1
        s = t[a0:(t.find('。', m.start()) + 1) or len(t)]
        a = max(a0, m.start() - 40); b = t.find('。', m.end()); b = min(m.end() + 40, b if b >= 0 else len(t))
        if (re.search(FUND_REL, s) and not re.search(FUND_NEG, t[a:b]) and not re.search(FUND_SELLER, s)
                and re.search(r'公開買付者|(発行済株式|議決権|持分)(総数)?(の(全て|すべて|全部|過半)|の?[0-9.]+%)', s)):
            return 1, ev(s[:300], '買付けの目的の冒頭：ファンドが買付者を所有・運営')
    return 0, ''


MBO_WORD = r'(マネジメント・?バイアウト(\(MBO\))?|MBO)(\(注[0-9]*\))?'


def mbo_any(c):
    """MBO（ファンドの有無を問わない）。1 = 書類が本取引を「マネジメント・バイアウト（MBO）」に該当すると明記している。
    見る段：すべての段落（括弧内の句点を除いてから読む）。
    該当表現：「本取引は、いわゆるMBOに該当し」「MBOの一環として」「MBOのための一連の取引」、
    適時開示の表題「MBOの実施及び応募の推奨に関するお知らせ」など。
    経営者の出資比率などから推定するのではなく、書類自身の位置付けに従う。
    除外表現：「該当しない／一環として行われるものではない」、MBO の定義の注記（「MBOとは、…」）、過去の事例・実例、
    当初提案（経緯の説明）、仮定。否定は該当箇所の前後40字で確認する"""
    t = _flat(_all(c))
    pos = [r'(本取引|本公開買付け|本件)[^。]{0,60}(いわゆる)?' + MBO_WORD + r'(取引)?(に該当|の一環|のための一連の取引|として(実施|行われ))',
           r'いわゆる' + MBO_WORD + r'(取引)?(に該当|の一環|のための一連の取引)',
           r'MBOの実施(及び|並びに)', r'公開買付け\(MBO\)の実施', r'非公開化\((マネジメント・?バイアウト\()?MBO\)']
    neg = [r'該当(しない|せず|しません|いたしません|するものではな)|ものではな|ではありません|ではなく|予定されておらず|予定はなく|事例|実例|案件|とは、|一般に|一般的|指針|準ずる'
           r'|可能性|場合には|仮に|当初提案']
    return R(hitw(pos, t, neg=neg, w=40))


def mbo(c):
    """MBO（ファンドが関わらないもの）。1 = mbo_any が 1 で、かつ fund が 0 である。
    fund が 1 の案件は「ファンド」に区分し、MBO は 0 とする（区分の方針は上の注記を参照）"""
    return (0, '') if fund(c)[0] else mbo_any(c)


