#!/bin/zsh
# 論文の数値をすべて計算し直す。結果は 再現/結果/、途中の表は 再現/中間/ に出る。
# データはこのリポジトリに含めていないため、先に README のとおりに data/・data_old/ などを置いておく必要がある。
# 実行方法：./再現/全部実行.sh（Python を変えるときは PY=/path/to/python3 ./再現/全部実行.sh）
# 12_標本規則の確認.py と 03_予測比較.py（以前の版の予測比較）はここでは実行しないので、必要なら個別に実行する。
set -e
cd "$(dirname "$0")"
mkdir -p 中間 結果
PY=${PY:-python3}
(cd ../program_vars && $PY build_all.py)      # 書類から取引条件11項目をプログラム（rules.py）で判定する
$PY 00a_収益と価格差.py                        # J・価格差・張り付き・20営業日の超過収益を株価と原文から計算する
