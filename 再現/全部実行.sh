$PY 00c_買付期間末日.py                        # 当初の買付期間の末日と、そこまでの収益（R1・W1）
$PY 01_分析表.py                               # 分析表（生成AIの判定は入れない）
$PY 02_回帰.py R1                              # 主な結果（回帰）
$PY 03b_予測比較_条件.py R1                    # 予測誤差の比較
$PY 04_注目度.py                               # 注目度
$PY 05_買付価格の照合.py                       # 買付価格を原文と照合する
